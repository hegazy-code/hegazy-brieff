# ── STATE MANAGEMENT ──────────────────────────────────────────────

def _load_state() -> dict:
    try:
        return json.loads(STATE_PATH.read_text()) if STATE_PATH.exists() else {}
    except Exception:
        return {}

def _save_state(state: dict) -> None:
    STATE_PATH.parent.mkdir(parents=True, exist_ok=True)
    STATE_PATH.write_text(json.dumps(state, indent=2, ensure_ascii=False))

def now_iso() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")

# ── HEALTH CHECK ──────────────────────────────────────────────────────────────

def _ping(source: dict) -> tuple[bool, str]:
    """Ping a source and return (ok, message)."""
    url = source.get("feed_url") or source.get("url")
    if not url:
        return False, "no URL"
    if source["retrieval"] == "sdk":
        return True, "sdk — not pinged directly"
    if source["retrieval"] == "api" and source.get("api_key_env"):
        if not os.environ.get(source["api_key_env"]):
            return False, f"missing env var {source['api_key_env']}"
    try:
        r = requests.head(url, timeout=TIMEOUT, allow_redirects=True,
                          headers={"User-Agent": "HegazyBrief/2.0 health-check"})
        if r.status_code < 400:
            return True, f"HTTP {r.status_code}"
        return False, f"HTTP {r.status_code}"
    except requests.exceptions.Timeout:
        return False, "timeout"
    except requests.exceptions.ConnectionError as e:
        return False, f"connection error: {e}"
    except Exception as e:
        return False, str(e)

def check_all(sources: Optional[list[dict]] = None, save: bool = True) -> dict:
    """
    Ping every source and return updated state dict.
    Pass sources=SOURCES to check all, or a subset for targeted checks.
    """
    targets = sources or SOURCES
    state = _load_state()
    for src in targets:
        sid = src["id"]
        s = state.setdefault(sid, {"last_ok": None, "last_fail": None, "fail_count": 0, "status": "unknown"})
        ok, msg = _ping(src)
        ts = now_iso()
        if ok:
            s.update(last_ok=ts, fail_count=0, status="up", last_msg=msg)
            log.info("✓ %s (%s)", src["name"], msg)
        else:
            s["fail_count"] = s.get("fail_count", 0) + 1
            s.update(last_fail=ts, status="down" if s["fail_count"] >= 3 else "degraded", last_msg=msg)
            log.warning("✗ %s: %s (fail #%d)", src["name"], msg, s["fail_count"])
        time.sleep(0.3)
    if save:
        _save_state(state)
    return state

# ── QUERY HELPERS ─────────────────────────────────────────────────────────────

def by_id(source_id: str) -> Optional[dict]:
    return next((s for s in SOURCES if s["id"] == source_id), None)

def by_sector(sector: str) -> list[dict]:
    return [s for s in SOURCES if sector in s.get("sectors", [])]

def by_region(region: str) -> list[dict]:
    return [s for s in SOURCES if region in s.get("regions", [])]

def official_sources() -> list[dict]:
    return [s for s in SOURCES if s.get("official")]

def healthy(state: dict, source_id: str) -> bool:
    """Return True if source is up or unknown (give benefit of doubt on first run)."""
    s = state.get(source_id, {})
    return s.get("status", "unknown") in ("up", "unknown")

def registry_report(state: dict) -> str:
    """Human-readable registry status for logs and coverage emails."""
    lines = ["SOURCE REGISTRY STATUS", "=" * 50]
    up = down = degraded = unknown = 0
    for src in sorted(SOURCES, key=lambda s: (s["priority"], s["id"])):
        s = state.get(src["id"], {})
        status = s.get("status", "unknown")
        last_ok = s.get("last_ok", "never")
        msg = s.get("last_msg", "")
        lines.append(f"[{status.upper():8s}] P{src['priority']} {src['id']:25s} {src['name']} ({last_ok}) {msg}")
        if status == "up": up += 1
        elif status == "down": down += 1
        elif status == "degraded": degraded += 1
        else: unknown += 1
    lines.append("")
    lines.append(f"Total: {len(SOURCES)} | UP: {up} | DEGRADED: {degraded} | DOWN: {down} | UNKNOWN: {unknown}")
    return "\n".join(lines)

